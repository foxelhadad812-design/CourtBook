using CourtBook.Application.DTOs;
using CourtBook.Application.Interfaces;
using CourtBook.Domain.Enums;
using CourtBook.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;

namespace CourtBook.Infrastructure.Services;

public class TermsService : ITermsService
{
    private readonly AppDbContext _db;

    public TermsService(AppDbContext db)
    {
        _db = db;
    }

    public async Task<TermsDocumentDto?> GetActiveTermsAsync(TermsType type)
    {
        var doc = await _db.TermsDocuments
            .AsNoTracking()
            .Where(t => t.Type == type && t.IsActive)
            .OrderByDescending(t => t.PublishedAt)
            .FirstOrDefaultAsync();

        if (doc is null) return null;

        var (titleAr, contentAr) = type switch
        {
            TermsType.FacilityOwner => (
                "متطلبات واتفاقية شراكة ملاك المنشآت الرياضية (الإصدار 1.0)",
                @"بلاي سبوت مصر — متطلبات وشروط شراكة ملاك المنشآت الرياضية (الإصدار 1.0)
تاريخ التحديث: سبتمبر 2026

1. إدراج المنشأة والاعتماد الرسمي
- يجب أن يمتلك مالك أو مدير المنشأة الصلاحيات القانونية أو التراخيص التجارية لإدارة وتأجير المجمع الرياضي واستقبال الحجوزات.
- توضع كافة المنشآت الرياضية الجديدة في حالة 'قيد المراجعة' حتى التحقق والاعتماد الرسمي من إدارة منصة بلاي سبوت.

2. معايير جودة الملاعب والسلامة
- تلتزم المنشأة بالمحافظة الدائمة على نظافة وسلامة الملاعب وصلاحية الأرضيات للعب (مثل النجيل الصناعي المعتمد، الزجاج البانورامي المقاوم للصدمات، الشباك القانونية).
- تشغيل الإضاءة الكاشفة، غرف تبديل الملابس، وتوفير حقيبة الإسعافات الأولية خلال جميع أوقات التشغيل.

3. دقة جدول المواعيد ومنع التعارض
- يلتزم مالك المنشأة بالحفاظ على جدول مواعيد دقيق ومحدث لحظياً عبر المنصة لمنع أي تضارب في المواعيد.
- يجب الالتزام التام بكافة الحجوزات المؤكدة للاعبين عبر بلاي سبوت، ولا يجوز للمالك إلغاء حجز مؤكد إلا لأسباب قاهرة مع تقديم إخطار مسبق لإدارة المنصة.

4. المستحقات والعمولات والتحصيل
- يجب وضوح أسعار الملاعب وساعات الذروة وشروط الإلغاء على المنصة دون أي رسوم خفية.
- تتم تسوية الحسابات المالية الخاصة بالحجوزات المؤكدة وفقاً للاتفاقية التجارية المبرمة."
            ),
            _ => (
                "شروط وقواعد استخدام منصة بلاي سبوت للاعبين (الإصدار 1.0)",
                @"بلاي سبوت مصر — شروط وقواعد استخدام اللاعبين (الإصدار 1.0)
تاريخ التحديث: سبتمبر 2026

1. الحساب والأهلية القانونية
بالتسجيل كلاعب في منصة بلاي سبوت، تقر بأنك تبلغ من العمر 16 عاماً على الأقل ومؤهل قانوناً لإبرام العقود والاتفاقيات الملزمة في جمهورية مصر العربية، وتتعهد بتقديم بيانات صحيحة ودقيقة.

2. حجوزات الملاعب والالتزامات
- يُعد الحجز عبر منصة بلاي سبوت التزاماً قانونياً ورياضياً مؤكداً مع المنشأة الرياضية المعنية.
- يلتزم اللاعب بالحضور إلى الملعب قبل موعد المباراة بـ 10 دقائق على الأقل.
- يتم سداد قيمة الحجز في مقر المنشأة قبل الدخول إلى أرضية الملعب ما لم يتم السداد إلكترونياً مسبقاً.

3. سياسة الإلغاء وعدم الحضور
- يحق للاعب إلغاء الحجز مجاناً بالكامل خلال نافذة الإلغاء المجاني المحددة للمنشأة (عادة 24 ساعة قبل موعد المباراة).
- في حالة الإلغاء المتأخر، يتم تطبيق غرامة الإلغاء المحددة في تفاصيل الحجز.
- تكرار التخلف عن الحضور (No-Show) قد يؤدي إلى تعليق أو إلغاء صلاحيات الحجز مؤقتاً أو نهائياً.

4. السلامة والسلوك الرياضي في المنشأة
- يجب الالتزام بالروح الرياضية والتعليمات الخاصة بالمنشأة وارتداء الأحذية المناسبة لنوع الأرضية (مثل الأحذية التي لا تترك أثراً في الصالات المغطاة، أو أحذية الترتان في ملاعب النجيل الصناعي).
- منصة بلاي سبوت وسيط تقني لتسهيل الحجوزات ولا تتحمل مسؤولية الإصابات الرياضية أو المفقودات الشخصية داخل المنشآت."
            )
        };

        return new TermsDocumentDto
        {
            Id = doc.Id,
            Type = doc.Type,
            Version = doc.Version,
            Title = doc.Title,
            Content = doc.Content,
            TitleAr = titleAr,
            ContentAr = contentAr,
            PublishedAt = doc.PublishedAt
        };
    }
}
